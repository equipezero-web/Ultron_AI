import { mobileBridgeSummary } from './bridge-status.js?v=5.15.0';
const button = document.getElementById('btn-pair-mobile');
const output = document.getElementById('output-box');

function setText(id, value) {
  const element = document.getElementById(id);
  if (element) element.textContent = String(value);
}

function log(message, alert = false) {
  if (!output) return;
  const line = document.createElement('p');
  if (alert) line.className = 'alert';
  line.textContent = `> [MOBILE LINK] ${message}`;
  output.appendChild(line);
  output.scrollTop = output.scrollHeight;
}

let lastGatewayAlertAt = 0;
let lastResult = { status: 'checking', online: false, paired: false };
let pairingDeadlineAt = 0;
let activePairingCode = '';
let isRefreshing = false;
let connecting = false;

async function refresh() {
  if(isRefreshing) return lastResult;
  isRefreshing = true;
  try {
    const api = window.ULTRON_DEVICES;
    if (typeof api?.listDevices !== 'function') {
      throw new Error('Módulo de dispositivos ainda não inicializado.');
    }
    // Never mistake network errors for "no paired devices".
    const devices = await api.listDevices();
    if (!Array.isArray(devices)) throw new Error('Gateway retornou uma lista inválida.');
    const streaming = window.ULTRON_MOBILE_CAMERA?.state?.active === true;
    const result = mobileBridgeSummary(devices, { streaming });
    lastResult = result;
    if (result.paired) { pairingDeadlineAt = 0; activePairingCode = ''; }
    if (!result.paired) {
      const code = String(document.getElementById('bridge-session-state')?.textContent || '');
      const pairing = String(document.getElementById('bridge-link-state')?.textContent || '') === 'PAIRING';
      if (pairing && /^CODE \d{6}$/.test(code) && !activePairingCode) {
        // The initial code may have been generated by the optical module.
        activePairingCode = code.slice(5);
        pairingDeadlineAt = Date.now() + 10 * 60_000;
      }
      if (activePairingCode && Date.now() < pairingDeadlineAt) {
        lastResult = { ...result, status: 'pairing', label: 'PAIRING', session: 'CODE ' + activePairingCode };
        setText('bridge-link-state', 'PAIRING');
        setText('bridge-session-state', lastResult.session);
        return lastResult;
      }
      activePairingCode = '';
      pairingDeadlineAt = 0;
    }
    setText('bridge-link-state', result.label);
    setText('bridge-device-name', result.device?.deviceName || 'NÃO CONECTADO');
    setText('bridge-session-state', result.session);
    if (!result.online) setText('bridge-camera-state', 'STANDBY');
    return result;
  } catch(error) {
    const message = String(error?.message || error || 'Falha desconhecida').slice(0,160);
    lastResult = { status: 'gateway-error', online: false, paired: null, error: message };
    setText('bridge-link-state', 'GATEWAY OFF');
    setText('bridge-session-state', 'SEM RESPOSTA');
    setText('bridge-device-name', 'NÃO VERIFICADO');
    setText('bridge-camera-state', 'STANDBY');
    if (Date.now() - lastGatewayAlertAt > 60_000) {
      log('Não foi possível consultar dispositivos no backend: ' + message, true);
      lastGatewayAlertAt = Date.now();
    }
    return lastResult;
  } finally {
    isRefreshing = false;
  }
}

// Pairing is a separate operation from remote-camera activation. The
// "CONECTAR CELULAR" button must work even without camera permissions.
async function connect() {
  if (connecting) return false;
  connecting = true;
  try {
    const result = await refresh();
    if (result.status === 'gateway-error') {
      log('Cloud indisponível: ' + (result.error || 'não foi possível consultar dispositivos') +
          '. Não foi criado um pareamento fictício.', true);
      return false;
    }
    if (result.status === 'pairing' && activePairingCode && Date.now() < pairingDeadlineAt) {
      const minutes = Math.max(1, Math.ceil((pairingDeadlineAt - Date.now()) / 60000));
      log('Código ' + activePairingCode + ' ainda válido por cerca de ' + minutes +
          ' minuto(s). Digite no aplicativo Ultron Bridge, depois toque em INICIAR BRIDGE.');
      return result;
    }
    if (!result.paired) {
      const api = window.ULTRON_DEVICES;
      if (typeof api?.startPairing !== 'function') {
        log('O módulo de pareamento não está disponível. Atualize a página.', true);
        return false;
      }
      const pairing = await api.startPairing('mobile', 'Ultron Mobile Bridge');
      const code = String(pairing?.code || '');
      if (!/^\d{6}$/.test(code)) throw new Error('O servidor não retornou um código válido.');
      activePairingCode = code;
      pairingDeadlineAt = Date.now() + Math.max(60, Number(pairing.expiresInSeconds) || 600) * 1000;
      lastResult = { ...result, status: 'pairing', label: 'PAIRING', session: 'CODE ' + code };
      setText('bridge-link-state', 'PAIRING');
      setText('bridge-session-state', lastResult.session);
      setText('bridge-device-name', 'ULTRON MOBILE BRIDGE');
      log('PAREAMENTO // Código ' + code +
          '. No Android, abra Ultron Bridge → PAREAR CELULAR, informe o código e INICIAR BRIDGE.');
      return lastResult;
    }
    if (!result.online) {
      log('Celular já pareado, porém OFFLINE. Abra o Ultron Bridge neste celular e toque em INICIAR BRIDGE. Depois consulte novamente.');
      return result;
    }
    log('Celular ONLINE / autenticado pelo Cloud. Para abrir a câmera, use CONECTAR CÂMERA DO CELULAR no Optical Sensor.');
    return result;
  } catch(error) {
    log('Não foi possível verificar ou parear o celular: ' +
      String(error?.message || error).slice(0,160), true);
    return false;
  } finally {
    connecting = false;
  }
}

let lastMobilePointerAt=0;
button?.addEventListener('pointerdown',event=>{
  if(event.button!==0)return;
  lastMobilePointerAt=Date.now();
  void connect();
},true);
button?.addEventListener('click',event=>{
  event.preventDefault();
  event.stopImmediatePropagation();
  if(Date.now()-lastMobilePointerAt<850)return;
  void connect();
},true);

window.addEventListener('ultron:mobile-camera-source', (event) => {
  if (!event?.detail?.active) return;
  setText('bridge-link-state', 'ONLINE');
  setText('bridge-session-state', 'STREAMING');
  setText('bridge-camera-state', 'ONLINE');
});

window.addEventListener('ultron:remote-camera-ice-recovery', (event) => {
  const state = String(event?.detail?.state || '');
  if (state === 'recovered') setText('bridge-session-state', 'STREAMING');
  else if (state === 'grace') setText('bridge-session-state', 'RECOVERING');
});

setTimeout(refresh, 900);
setInterval(refresh, 7000);

window.ULTRON_MOBILE_LINK = { connect, refresh, version: '5.16.0', get state(){ return lastResult; } };
