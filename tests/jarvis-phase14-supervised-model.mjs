import assert from "node:assert/strict";
import {parseSupervisedCommand,buildSupervisedPlan,checkSupervisedPlan} from "../modules/jarvis-supervised-autonomy-model.js";
const now=Date.parse("2026-11-13T16:00:00Z");
assert.deepEqual(parseSupervisedCommand("Jarvis, planeje uma análise das notícias"),{type:"plan",kind:"briefing"});
assert.deepEqual(parseSupervisedCommand("autorizar plano"),{type:"approve"});
assert.deepEqual(parseSupervisedCommand("cancelar plano"),{type:"cancel"});
assert.equal(parseSupervisedCommand("apague arquivos e envie emails"),null);
assert.equal(parseSupervisedCommand("ligue a camera"),null);
assert.equal(parseSupervisedCommand("compre produtos"),null);
const p=buildSupervisedPlan("briefing",{now});
assert.equal(p.steps.length,2);
assert.equal(checkSupervisedPlan(p,{now:now+119999}).ok,true);
assert.equal(checkSupervisedPlan(p,{now:now+120000}).reason,"PLAN_EXPIRED");
assert.equal(buildSupervisedPlan("event",{now}).reason,"NO_VERIFIED_SELECTED_EVENT");
const current={ok:true,eventKey:"g:usgs1",url:"https://earthquake.usgs.gov/earthquakes/eventpage/usgs1"};
const e=buildSupervisedPlan("event",{current,now});
assert.equal(e.ok,true);
assert.equal(checkSupervisedPlan(e,{current:{...current,eventKey:"g:changed"},now}).reason,"EVENT_CHANGED");
assert.equal(checkSupervisedPlan(e,{current,now}).ok,true);
console.log("PHASE XIV MODEL PASS: explicit approval, expiry, source continuity and side-effect isolation");
