import assert from "node:assert/strict";
import {GEO_SCENARIOS,GEO_SOURCE,GEO_PALETTE,geoFrame,validateGeoScenario,brazilXY,geoJSONPaths} from "../modules/jarvis-geospatial-model.js";
import {validatePlan,isActionRequest} from "../backend/action-catalog.js";
import {directPlan} from "../modules/jarvis-action-engine.js";
const dataset=validateGeoScenario(GEO_SCENARIOS.enso);
assert.ok(dataset?.source?.url.includes("gov.br/cemaden"));
assert.equal(dataset.frames.length,3);
assert.deepEqual(dataset.frames.map(f=>f.kind),["observed","forecast","illustrative"]);
assert.match(GEO_SOURCE.disclaimer,/Não são limites de desastre/);
assert.ok(dataset.frames[1].points.some(p=>p.name==="Sul do Brasil"&&p.kind==="wet"));
assert.ok(dataset.frames[1].points.some(p=>p.kind==="dry"));
assert.ok(dataset.frames[1].points.some(p=>p.kind==="heat"));
assert.ok(geoFrame(dataset,1,"wet").points.every(p=>p.kind==="wet"));
assert.ok(geoFrame(dataset,0,"wet").points.length===0);
assert.equal(geoFrame(dataset,999).index,2);
assert.equal(geoFrame(dataset,-1).index,0);
assert.equal(geoFrame(dataset,1,"invalid").points.length,0);
assert.equal(validateGeoScenario({...GEO_SCENARIOS.enso,source:{name:"Sem fonte",url:"javascript:alert(1)",disclaimer:"... "}}),null);
assert.equal(validateGeoScenario({...GEO_SCENARIOS.enso,frames:[{id:"x",points:[{lat:200,lng:12,name:"Inválido",kind:"dry",detail:"..." }]}]}),null);
const outline=geoJSONPaths({type:"FeatureCollection",features:[{type:"Feature",geometry:{type:"Polygon",coordinates:[[[-70,-1],[-50,-1],[-50,-30],[-70,-1]]]}}]});
assert.equal(outline.length,1);
assert.ok(outline[0].startsWith("M")&&outline[0].endsWith("Z"));
const p=brazilXY(-51,-14);assert.ok(p.x>55&&p.x<850&&p.y>50&&p.y<550);
assert.ok(validatePlan({steps:[{action:"geo.show",args:{scenario:"enso",view:"2d"}}]}));
assert.equal(validatePlan({steps:[{action:"geo.show",args:{scenario:"future_climate",view:"3d"}}]}),null);
assert.equal(validatePlan({steps:[{action:"geo.filter",args:{kind:"quantitative_forecast"}}]}),null);
assert.equal(validatePlan({steps:[{action:"geo.show",args:{scenario:"enso",view:"hologram"}}]}),null);
assert.equal(isActionRequest("JARVIS, crie uma simulação 3D do El Niño"),true);
assert.equal(directPlan("JARVIS, mostre no globo as áreas de impacto do El Niño").steps[0].action,"geo.show");
assert.deepEqual(directPlan("JARVIS, crie uma simulação 2D do El Niño").steps[0].args,{scenario:"enso",view:"2d"});
assert.equal(directPlan("Como posso criar uma simulação do El Niño?"),null);
assert.equal(directPlan("Qual é a intensidade exata do El Niño em Pernambuco?"),null);
console.log("JARVIS PHASE 3 PASS: sourced seasonal framing, geographic projection, strict action arguments and real visualization routing");
