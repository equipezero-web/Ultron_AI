import assert from "node:assert/strict";
import {normalizeIntent,splitOperatorSteps,classifyOperatorTurn,isPrivateTurn} from "../modules/jarvis-intent-engine.js";
import {createTaskContext} from "../modules/jarvis-task-context.js";

assert.equal(normalizeIntent("JARVIS, agora foque no Nordeste!"),"agora foque no nordeste!");
assert.equal(classifyOperatorTurn("Como posso abrir o globo?").kind,"question");
assert.equal(classifyOperatorTurn("Se eu desligar meu PC, o que acontece?").kind,"negated");
assert.equal(classifyOperatorTurn("JARVIS, desative os textos").kind,"command");
assert.equal(classifyOperatorTurn("E no Nordeste?").kind,"follow-up");
assert.equal(splitOperatorSteps("O que aconteceu depois da tempestade?").length,1);
assert.equal(splitOperatorSteps("Pesquise sobre o El Niño e depois abra o globo; verifique o estado do sistema").length,3);
assert.equal(splitOperatorSteps("Pesquise as consequências e em seguida me mostre o mapa").length,2);
assert.equal(isPrivateTurn("Qual o meu saldo?"),true); // Never send private banking context to public search
assert.equal(isPrivateTurn("Meu saldo atual é R$500"),true);
let clock=Date.parse("2026-11-11T09:00:00Z"),conversation="chat-1";
const store=new Map(),storage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v),removeItem:k=>store.delete(k)};
const config={storage,now:()=>clock,conversationId:()=>conversation};
const tracker=createTaskContext(config);
tracker.captureQuestion("Analise os impactos do El Niño no Brasil");
let state=tracker.snapshot();
assert.match(state.topic,/El Niño/i);
assert.equal(state.region,"Brasil");
assert.match(state.lastPublicQuestion,/impactos do El Niño/);
let followup=tracker.resolve("E no Nordeste?");
assert.equal(followup.kind,"contextual-question");
assert.equal(followup.region,"nordeste");
assert.match(followup.researchQuery,/El Niño/);
assert.deepEqual(tracker.publicContextFor("E no Nordeste?").followup,true);
tracker.recordAction({action:"earth.open"},{ok:true});
assert.equal(tracker.snapshot().visualization,"globe");
const command=tracker.resolve("Agora foque no Nordeste");
assert.equal(command.kind,"contextual-action");
assert.equal(command.command,"Localize nordeste no globo");
tracker.recordAction({action:"earth.locate",args:{place:"Nordeste"}},{ok:true});
assert.equal(tracker.snapshot().region,"Nordeste");
tracker.recordAction({action:"earth.close"},{ok:true});
assert.equal(tracker.snapshot().visualization,"ring");
const comparison=tracker.resolve("Compare com o Sul");
assert.equal(comparison.kind,"contextual-question");
assert.match(comparison.researchQuery,/El Niño/);
tracker.captureQuestion("Minha senha é abc123");
assert.ok(!JSON.stringify(tracker.snapshot()).includes("abc123"));
assert.equal(tracker.publicContextFor("Qual minha senha?"),null);
let restored=createTaskContext(config);
assert.equal(restored.snapshot().topic,tracker.snapshot().topic);
conversation="chat-2";
assert.equal(restored.snapshot().topic,"");
conversation="chat-1";
restored=createTaskContext(config);
clock+=2*60*60*1000+1;
assert.equal(restored.snapshot().topic,"");
console.log("JARVIS PHASE 1 PASS: typed/voice intent, non-ambiguous sequences, contextual focus, private-safe scoped memory, expiration and reset");
